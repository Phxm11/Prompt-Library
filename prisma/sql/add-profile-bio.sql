-- เพิ่มไบโอสั้น ๆ ให้โปรไฟล์
--
-- ฝั่งเว็บจำกัดไว้ที่ 50 ตัวอักษรแบบที่ตามองเห็น (grapheme) แต่คอลัมน์ต้องเผื่อกว้างกว่านั้นมาก
-- เพราะภาษาไทยหนึ่งตัวที่ตาเห็นกินได้ถึง 3-4 หน่วยในสายอักขระ เช่น "เก้" หรือ "ทั้ง"
-- ถ้าตั้ง varchar(50) ตรงตัว คนพิมพ์ไทยเต็ม 50 ตัวจะโดน Postgres ปฏิเสธด้วย error 22001
-- ตัวเลข 300 มาจาก 50 ตัว x 4 หน่วย บวกเผื่ออีกนิด

alter table public.profiles
  add column if not exists bio varchar(300);

comment on column public.profiles.bio is
  'ข้อความแนะนำตัวสั้น ๆ จำกัด 50 ตัวอักษรที่ฝั่งเว็บ';
